(async()=>{
 const results=[];
 const sleep=ms=>new Promise(r=>setTimeout(r,ms));
 const until=async(fn,name)=>{const end=Date.now()+12000;while(!fn()){if(Date.now()>end)throw Error('Timeout: '+name);await sleep(40);}};
 const visible=e=>e.getClientRects().length>0&&!e.closest('[inert]')&&!e.closest('dialog:not([open])');
 const btn=label=>[...document.querySelectorAll('button')].filter(visible).find(b=>b.getAttribute('aria-label')===label||b.textContent.trim()===label);
 const click=async label=>{const b=btn(label);if(!b||b.disabled)throw Error('Botão indisponível: '+label);b.click();await sleep(350);};
 const assert=(condition,label)=>{if(!condition)throw Error(label);results.push(label);};
 const text=(value)=>{const el=document.querySelector('#pergunta');Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(el,value);el.dispatchEvent(new Event('input',{bubbles:true}));};
 const send=async value=>{text(value);await until(()=>!btn('Enviar pergunta').disabled,'envio habilitado');await click('Enviar pergunta');};
 const response=()=>until(()=>!document.querySelector('#pergunta').readOnly,'resposta completa');
 assert(!document.querySelector('video'),'Mobile sem elemento de vídeo');
 assert(!performance.getEntriesByType('resource').some(r=>/study-loop|study-poster/.test(r.name)),'Mobile sem download de vídeo e poster');
 assert(document.documentElement.scrollWidth<=innerWidth,'Sem rolagem horizontal');
 await click('Entender um conceito');
 assert(document.querySelector('#pergunta').value.includes('assertiva'),'Exemplo editável, sem envio automático');
 assert(!document.querySelector('.td-user-message'),'Exemplo não cria mensagem');
 await click('Enviar pergunta');await response();
 assert(document.querySelector('.td-answer-text').textContent.includes('respeito'),'Resposta de estudo');
 await click('Resposta útil');assert(btn('Resposta útil').getAttribute('aria-pressed')==='true','Avaliação por teclado/controle');
 await send('Onde peço meu atestado de matrícula?');
 assert(!!btn('Ir para o atendimento'),'Encaminhamento institucional explícito');
 assert(document.querySelectorAll('.td-answer').length===1,'Sem resposta institucional antes da escolha');
 await click('Editar pergunta');
 assert(document.querySelector('#pergunta').value.includes('atestado'),'Pergunta preservada ao editar');
 await click('Enviar pergunta');await click('Ir para o atendimento');await response();
 assert([...document.querySelectorAll('.td-answer-heading')].at(-1).textContent.includes('Atendimento da faculdade'),'Destino da resposta visível');
 await click('Nova conversa');await click('Desfazer');
 await until(()=>document.querySelectorAll('.td-answer').length===2,'restauração após transição');assert(true,'Limpar e desfazer restaura conversa');
 await click('Nova conversa');await send('Preciso de ajuda');
 assert(!!btn('Conteúdo da matéria'),'Intenção ambígua pede esclarecimento');
 await click('Prefiro reformular a pergunta');
 await send('Explique assertividade e como pegar meu boleto');
 assert(document.body.textContent.includes('uma dúvida de cada vez'),'Mensagem com dois destinos não mistura bases');
 await click('Editar minha pergunta');
 await click('Nova conversa');
 await click('Abrir espaço de estudo');
 assert(!!document.querySelector('dialog[open]'),'Ferramentas acessíveis em diálogo mobile');
 const dialog=document.querySelector('dialog[open]');
 dialog.dispatchEvent(new Event('cancel',{cancelable:true}));await sleep(350);
 assert(!document.querySelector('dialog[open]'),'Escape fecha diálogo');
 await click('Abrir espaço de estudo');
 const quiz=[...document.querySelectorAll('dialog[open] button')].find(b=>b.textContent.includes('Quiz'));
 quiz.click();await until(()=>document.querySelector('.td-tool-workspace[open]'),'ferramenta modal');
 await until(()=>btn('Começar quiz'),'quiz carregado');
 assert(!!btn('Começar quiz'),'Quiz preservado no mobile');
 document.querySelector('.td-tool-workspace').dispatchEvent(new Event('cancel',{cancelable:true}));await sleep(350);
 assert(!document.querySelector('dialog[open]'),'Escape retorna ao chat da ferramenta');
 if(btn('Usar tema escuro'))await click('Usar tema escuro');
 assert(document.documentElement.dataset.theme==='dark','Tema escuro disponível');
 assert(!performance.getEntriesByType('resource').some(r=>new URL(r.name).origin!==location.origin),'Sem requisições externas');
 return results;
})();
