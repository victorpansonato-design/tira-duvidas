(async()=>{
 const wait=ms=>new Promise(r=>setTimeout(r,ms));
 const until=async(fn,label)=>{const end=Date.now()+15000;while(!fn()){if(Date.now()>end)throw Error(label);await wait(50);}};
 const out={};
 const assert=(v,label)=>{if(!v)throw Error(label);out[label]=true;};
 assert(getComputedStyle(document.querySelector('.td-app')).backgroundColor==='rgb(12, 12, 12)','Fundo escuro original');
 assert(getComputedStyle(document.querySelector('.td-chat')).backgroundColor==='rgb(32, 32, 32)','Painel original');
 assert(document.querySelector('.td-study-rail').getBoundingClientRect().width===420,'Caderno com 420px');
 assert(document.querySelector('.td-context').tagName==='SPAN','Disciplina estática, sem ação');
 const video=document.querySelector('video');
 await until(()=>video?.readyState>=2,'Vídeo não ficou pronto');
 assert(video.videoWidth===3840&&video.videoHeight===2160,'Vídeo 4K real');
 assert(video.muted&&video.loop&&!video.controls,'Vídeo mudo em loop, sem controle sobreposto');
 const start=video.currentTime;await wait(400);
 out.videoPlayback={paused:video.paused,visibility:document.visibilityState,advanced:video.currentTime!==start};
 assert(!video.paused&&video.currentTime!==start,'Reprodução automática funcionando');
 const button=label=>[...document.querySelectorAll('button')].find(b=>b.getClientRects().length&&(b.getAttribute('aria-label')===label||b.textContent.trim()===label));
 button('Reduzir movimento').click();await wait(80);
 assert(!document.querySelector('video'),'Preferência interrompe vídeo sem sobreposição');
 button('Ativar animações').click();await wait(80);
 button('Usar tema claro').click();
 assert(document.documentElement.dataset.trocaTema==='nascer','Tema usa a revelação circular original');await wait(900);
 button('Usar tema escuro').click();await wait(900);
 const input=document.querySelector('#pergunta');Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(input,'Me explique comunicação assertiva');input.dispatchEvent(new Event('input',{bubbles:true}));await wait(80);button('Enviar pergunta').click();
 await wait(450);out.firstPhase=document.querySelector('.td-thinking-label')?.textContent;
 await wait(1000);out.secondPhase=document.querySelector('.td-thinking-label')?.textContent;
 await wait(1000);const partial=document.querySelector('.td-answer-text')?.textContent||'';
 assert(partial.length>0&&input.readOnly,'Resposta aparece progressivamente após preparação');
 await until(()=>!input.readOnly,'Resposta não terminou');
 assert(document.querySelector('.td-answer-text').textContent.length>partial.length,'Texto continua até terminar');
 assert(!document.documentElement.dataset.trocaTema,'Transição de tema concluiu');
 return out;
})();
